"""Unit tests for the global_chat request payload."""

import pytest
from global_chat.app_map import APP_MAP_CHAR_LIMIT
from global_chat.global_chat import Payload
from util import ApolloError

BAD_REQUEST = 400


def test_web_search_defaults_to_off_when_options_are_absent() -> None:
    assert Payload.from_dict({"content": "hi"}).get_web_search() is False


def test_web_search_defaults_to_off_when_options_omit_the_key() -> None:
    assert Payload.from_dict({"content": "hi", "options": {"stream": True}}).get_web_search() is False


def test_web_search_is_read_from_options() -> None:
    payload = Payload.from_dict({"content": "hi", "options": {"web_search": True}})

    assert payload.get_web_search() is True


def test_app_map_defaults_to_none_when_absent() -> None:
    assert Payload.from_dict({"content": "hi"}).app_map is None


def test_app_map_is_accepted_as_a_list_of_page_objects() -> None:
    pages = [{"id": "project_history", "path": "/projects/:project_id/history", "label": "History"}]

    payload = Payload.from_dict({"content": "hi", "app_map": pages})

    assert payload.app_map == pages


@pytest.mark.parametrize(
    "bad_map",
    [
        "not a list",
        {"id": "a-page-not-wrapped-in-a-list"},
        ["a string entry"],
        [{"id": "ok"}, "then a string"],
        42,
    ],
)
def test_a_malformed_app_map_is_rejected_loudly(bad_map: object) -> None:
    """The map is machine-generated by the caller, so a wrong shape is an
    integration bug: a 400 surfaces it where dropping it would hide it."""
    with pytest.raises(ApolloError) as raised:
        Payload.from_dict({"content": "hi", "app_map": bad_map})

    assert raised.value.code == BAD_REQUEST
    assert "app_map" in raised.value.message


def test_an_oversized_app_map_is_rejected() -> None:
    big = [{"id": "page", "description": "x" * (APP_MAP_CHAR_LIMIT + 1)}]

    with pytest.raises(ApolloError) as raised:
        Payload.from_dict({"content": "hi", "app_map": big})

    assert raised.value.code == BAD_REQUEST
    assert "too large" in raised.value.message
