"""Validation and prompt rendering for the Lightning app map.

Lightning sends `app_map`: a JSON array of page entries describing every
user-facing page in its UI (id, path, module, label, section, description,
optional tabs). The planner gets it rendered as compact markdown so it can
tell users exactly where to go instead of guessing.
"""

import json
import sys
from pathlib import Path

sys.path.append(str(Path(__file__).parent.parent))

from util import ApolloError

# Generous cap on the serialised map, mirroring check_attachment_size's
# fail-loud stance: a map this large is an integration bug, not content to
# silently truncate. The real map is ~16KB; this allows ample growth.
APP_MAP_CHAR_LIMIT = 250_000

# Lightning's sections, in the order a user meets them. Unknown sections are
# not dropped — they sort after these, alphabetically, so a new section added
# upstream still renders.
_SECTION_ORDER = ["project", "user", "admin", "auth"]


def check_app_map(app_map: object) -> None:
    """Reject a malformed or oversized app_map before any model is called.

    Deliberately loud rather than lossy: the map is machine-generated by the
    caller, so a wrong shape is an integration bug a 400 surfaces immediately,
    where silently dropping it would just degrade answers.
    """
    if app_map is None:
        return

    if not isinstance(app_map, list) or not all(isinstance(entry, dict) for entry in app_map):
        raise ApolloError(400, "app_map must be a list of page objects")

    size = len(json.dumps(app_map))
    if size > APP_MAP_CHAR_LIMIT:
        raise ApolloError(
            400,
            f"app_map is too large: {size:,} characters against a "
            f"{APP_MAP_CHAR_LIMIT:,} limit.",
        )


def _section_key(section: str) -> tuple:
    try:
        return (_SECTION_ORDER.index(section), "")
    except ValueError:
        return (len(_SECTION_ORDER), section)


def _format_tab(tab: object) -> str | None:
    """One indented sub-bullet for a settings tab, or None to skip it."""
    if not isinstance(tab, dict):
        return None
    label = tab.get("label") or tab.get("hash")
    if not label:
        return None
    line = f"  - {label}"
    if tab.get("hash"):
        line += f" (#{tab['hash']})"
    description = tab.get("description")
    if description:
        line += f": {description}"
    return line


def _format_entry(entry: dict) -> list[str]:
    """The lines for one page entry, or [] to skip it.

    Keys are whatever the caller sent: a missing or wrong-typed key skips
    the line (or the whole entry), never crashes the request.
    """
    label = entry.get("label") or entry.get("id")
    path = entry.get("path")
    if not label and not path:
        return []

    line = f"- **{label or path}**"
    # The id is the handle the navigation directive points at (see
    # planner_app_map_prompt), so the model must see it on every page line.
    if entry.get("id"):
        line += f" [id: {entry['id']}]"
    if path:
        line += f" (`{path}`)"
    description = entry.get("description")
    if description:
        line += f": {description}"

    lines = [line]
    tabs = entry.get("tabs")
    if isinstance(tabs, list):
        lines.extend(tab_line for tab in tabs if (tab_line := _format_tab(tab)))
    return lines


def format_app_map(app_map: list[dict] | None) -> str:
    """Render the app map as compact markdown, grouped by section.

    Deterministic: sections in Lightning's canonical order (unknown sections
    after, alphabetically), pages within a section by label. Malformed
    entries are skipped rather than crashing the turn.
    """
    if not app_map:
        return ""

    sections: dict[str, list[dict]] = {}
    for entry in app_map:
        if not isinstance(entry, dict):
            continue
        section = entry.get("section")
        section = section if isinstance(section, str) and section else "other"
        sections.setdefault(section, []).append(entry)

    parts = []
    for section in sorted(sections, key=_section_key):
        entries = sorted(sections[section], key=lambda e: str(e.get("label") or e.get("id") or ""))
        lines = [line for entry in entries for line in _format_entry(entry)]
        if not lines:
            continue
        parts.append(f"### {section.capitalize()}")
        parts.extend(lines)

    return "\n".join(parts)
